#!/usr/bin/env node
// faraday-masthead · scripts/build.mjs (FDY-444). Regenerates every derived file from core.ts, so there is ONE source:
//   static/masthead.css            = MASTHEAD_CSS
//   static/masthead.html           = the static snippet with {{PLACEHOLDERS}} (for servers without React/TS)
//   ../faraday-gate/ui/gate.html   = its <header> region, between the faraday-masthead markers (canonical layout only)
//   MANIFEST.json                  = version + sha256 of every shipped file (what check-drift.mjs verifies)
// Run: node --experimental-strip-types --no-warnings packages/faraday-masthead/scripts/build.mjs [--check]
// --check writes nothing and exits 1 if anything is stale (CI).
import fs from "node:fs";
import path from "node:path";
import crypto from "node:crypto";
import { fileURLToPath, pathToFileURL } from "node:url";

const PKG = path.join(path.dirname(fileURLToPath(import.meta.url)), "..");
const CHECK = process.argv.includes("--check");
const core = await import(pathToFileURL(path.join(PKG, "core.ts")).href);

export const START = "<!-- faraday-masthead:start -->";
export const END = "<!-- faraday-masthead:end -->";

/** Static snippet: the masthead with placeholders a server fills (HTML-escaped values, except CONTEXT and WHO). */
export function staticTemplate() {
  const sentinel = { appName: "@@APP@@", homeHref: "@@HOME@@", skipTo: "@@SKIP@@", contextHtml: "@@CTX@@", signInHtml: "@@WHO@@" };
  return core.renderMastheadHtml(sentinel)
    .replaceAll("@@APP@@", "{{APP_NAME}}").replaceAll("@@HOME@@", "{{HOME}}").replaceAll("@@SKIP@@", "{{SKIP}}")
    .replaceAll("@@CTX@@", "{{CONTEXT}}").replaceAll("@@WHO@@", "{{WHO}}")
    .replace(/(aria-label="Open menu">)[^<]*(<\/button>)/, "$1{{INITIAL}}$2");
}

/** The masthead block the static gate page carries (app name filled server-side via the gate's {{APP_NAME}}). */
export function gateBlock() {
  return `<style data-fm-css="${core.MASTHEAD_VERSION}">${core.MASTHEAD_CSS}</style>` + core.renderMastheadHtml({ appName: "@@APP@@", homeHref: "/", signInHtml: "" })
    .replaceAll("@@APP@@", "{{APP_NAME}}")
    .replace(/(aria-label="Open menu">)[^<]*(<\/button>)/, "$1F$2");
}

const files = {
  "static/masthead.css": core.MASTHEAD_CSS + "\n",
  "static/masthead.html":
    "<!-- faraday-masthead " + core.MASTHEAD_VERSION + " · static snippet (generated by scripts/build.mjs from core.ts; do not edit).\n"
    + "     Include static/masthead.css once per page. Fill: {{APP_NAME}} {{HOME}} {{SKIP}} {{INITIAL}} (escaped), {{CONTEXT}} {{WHO}} (trusted HTML;\n"
    + "     WHO = <a class=\"fm-signin\" href=\"…\">Sign in</a> or <span class=\"fm-user\" title=\"email\">email</span>).\n     The trailing <script> is the optional narrow-screen menu toggle. -->\n"
    + staticTemplate() + "\n<script>" + core.MASTHEAD_SCRIPT + "</script>\n",
};

let stale = [];
function write(rel, content) {
  const p = path.join(PKG, rel);
  const cur = fs.existsSync(p) ? fs.readFileSync(p, "utf8") : null;
  if (cur === content) return;
  stale.push(rel);
  if (!CHECK) { fs.mkdirSync(path.dirname(p), { recursive: true }); fs.writeFileSync(p, content); }
}
for (const [rel, c] of Object.entries(files)) write(rel, c);

// Gate static page (only in the canonical layout, where ../faraday-gate exists).
const gateHtml = path.join(PKG, "..", "faraday-gate", "ui", "gate.html");
if (fs.existsSync(gateHtml)) {
  const src = fs.readFileSync(gateHtml, "utf8");
  const i = src.indexOf(START), j = src.indexOf(END);
  if (i < 0 || j < 0) { console.error("gate.html has no faraday-masthead markers"); process.exit(1); }
  const next = src.slice(0, i + START.length) + gateBlock() + src.slice(j);
  if (next !== src) { stale.push("../faraday-gate/ui/gate.html"); if (!CHECK) fs.writeFileSync(gateHtml, next); }
}

// Manifest last (it hashes the files above).
const SHIP = ["VERSION", "README.md", "core.ts", "ui/Masthead.tsx", "static/masthead.css", "static/masthead.html",
  "check-drift.mjs", "scripts/build.mjs", "test/masthead.test.ts", "test/render.test.mjs"];
const sha = (rel) => crypto.createHash("sha256").update(fs.readFileSync(path.join(PKG, rel))).digest("hex");
const version = fs.readFileSync(path.join(PKG, "VERSION"), "utf8").trim();
if (version !== core.MASTHEAD_VERSION) { console.error(`VERSION ${version} != core.MASTHEAD_VERSION ${core.MASTHEAD_VERSION}`); process.exit(1); }
const manifest = JSON.stringify({ package: "faraday-masthead", version, files: Object.fromEntries(SHIP.map((f) => [f, sha(f)])) }, null, 2) + "\n";
write("MANIFEST.json", manifest);

if (CHECK && stale.length) { console.error("faraday-masthead: stale generated files: " + stale.join(", ") + " — run scripts/build.mjs"); process.exit(1); }
console.log(CHECK ? "faraday-masthead: generated files up to date" : `faraday-masthead ${version}: wrote ${stale.length ? stale.join(", ") : "nothing (up to date)"}`);
